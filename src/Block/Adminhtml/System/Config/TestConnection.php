declare(strict_types=1);

namespace Innosend\Integration\Block\Adminhtml\System\Config;

use Magento\Config\Block\System\Config\Form\Field;

/**
 * Test connection button block
 */
class TestConnection extends Field
{
    /**
     * Set template to itself
     *
     * @return $this
     */
    protected function _prepareLayout()
    {
        parent::_prepareLayout();
        $this->setTemplate('Innosend_Integration::system/config/testconnection.phtml');
        return $this;
    }

    /**
     * Unset some non-related element parameters
     *
     * @param \Magento\Framework\Data\Form\Element\AbstractElement $element
     * @return string
     */
    public function render(\Magento\Framework\Data\Form\Element\AbstractElement $element)
    {
        $element = clone $element;
        $element->unsScope()->unsCanUseWebsiteValue()->unsCanUseDefaultValue();
        return parent::render($element);
    }

    /**
     * Get the button and scripts contents
     *
     * @param \Magento\Framework\Data\Form\Element\AbstractElement $element
     * @return string
     */
    protected function _getElementHtml(\Magento\Framework\Data\Form\Element\AbstractElement $element)
    {
        $originalData = $element->getOriginalData() ?? [];
        $this->addData(
            [
                'button_label' => __($originalData['button_label'] ?? 'Test Connection'),
                'html_id' => $element->getHtmlId(),
                'ajax_url' => $this->_urlBuilder->getUrl('innosend/system_config/testconnection'),
                'field_mapping' => str_replace('"', '\\"', json_encode($this->_getFieldMapping()))
            ]
        );

        return $this->_toHtml();
    }

    /**
     * Returns configuration fields required to perform the test connection
     * Field IDs are generated by Magento as: {section}_{group}_{field}
     *
     * @return array
     */
    protected function _getFieldMapping()
    {
        return [
            'enabled' => 'innosend_api_configuration_enabled',
            'mode' => 'innosend_api_configuration_mode',
            'organization_id' => 'innosend_api_configuration_organization_id',
            'api_key' => 'innosend_api_configuration_api_key',
            'api_secret' => 'innosend_api_configuration_api_secret',
            'api_token' => 'innosend_api_configuration_api_token',
            'test_endpoint' => 'innosend_api_configuration_test_endpoint',
            'live_endpoint' => 'innosend_api_configuration_live_endpoint',
            'timeout' => 'innosend_api_configuration_timeout'
        ];
    }
}
